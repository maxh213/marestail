def emit(target: str, fn: Call | None) -> None:
    if fn is None:
        harness.absent(target)
        return
    harness.emit(target, harness.measure(fn))


def restore_env(previous: str | None) -> None:
    if previous is None:
        os.environ.pop(ENV, None)
        return
    os.environ[ENV] = previous


def without_jobs(fn: Call) -> None:
    previous = os.environ.get(ENV)
    os.environ.pop(ENV, None)
    try:
        fn()
    finally:
        restore_env(previous)


def with_jobs(fn: Call) -> None:
    previous = os.environ.get(ENV)
    os.environ[ENV] = "3"
    try:
        fn()
    finally:
        restore_env(previous)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def go_file(folder: str, name: str, body: str) -> Path:
    path = state["root"] / folder / name
    write(path, body)
    return path


