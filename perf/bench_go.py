def profile_text() -> str:
    rows = ["mode: set"]
    for index in range(40):
        start = 2 + index
        rows.append(f"{MODULE}/internal/domain/domain.go:{start}.2,{start + 1}.4 1 {index % 3}")
        rows.append(f"{MODULE}/internal/domain/domain.go:{start}.2,{start + 1}.4 1 {(index % 3) + 1}")
    rows.append(f"{MODULE}/internal/store/store.go:4.2,6.8 1 1")
    rows.append(f"{MODULE}/internal/store/generated.go:1.1,1.2 1 0")
    rows.append(f"{MODULE}/internal/pkg/p0/code.go:1.1,2.2 1 0")
    rows.append("other.com/x.go:1.1,1.2 1 0")
    rows.append("not a block")
    return "\n".join(rows) + "\n"


def scan_records(command: list[str]) -> list[dict[str, Any]]:
    mode = command[1]
    paths: list[str] = []
    for part in command[2:]:
        if part == "--uses":
            break
        paths.append(part)
    if mode == "comments":
        return [{"file": path, "line": 1, "text": "// note"} for path in paths]
    if mode == "complexity":
        return [{"file": path, "name": "Classify", "line": 10, "end": 24, "complexity": 5} for path in paths]
    if mode == "depth":
        record = {"public": ["Classify", "Tag"], "statements": 12, "pass_throughs": [{"line": 4, "name": "Label", "target": "describe"}]}
        return [{"file": path, **record} for path in paths]
    if mode == "imports":
        return [{"file": path, "line": 6, "path": f"{MODULE}/internal/store"} for path in paths]
    if mode == "dead":
        return [{"file": path, "line": 3, "kind": "function", "name": "UnusedHelper"} for path in paths]
    return []


def pin_text(path: str) -> str:
    name = Path(path).name
    if name == "golangci-lint":
        return "\tmod\tgithub.com/golangci/golangci-lint/v2\tv2.13.2\n"
    if name == "gremlins":
        return "\tmod\tgithub.com/go-gremlins/gremlins\tv0.6.0\n"
    return "\tmod\tunknown\tv0.0.0\n"


class CoverageClient:
    def get(self, _path: str, **kwargs: Any) -> dict[str, Any]:
        if kwargs.get("metricKeys") == "coverage":
            return {"component": {"measures": [{"metric": "coverage", "value": 77.8}]}}
        return {"components": []}


def flag_value(command: list[str], flag: str) -> str | None:
    if flag not in command:
        return None
    return command[command.index(flag) + 1]


def lint_report() -> dict[str, Any]:
    issues = []
    for index in range(10):
        issues.append(
            {
                "FromLinter": "wastedassign",
                "Text": f"assigned to size {index}, but reassigned\nsecond",
                "Pos": {"Filename": str(state["store"]), "Line": 4 + index, "Column": 2},
            }
        )
    issues.append(issues[0])
    return {"Issues": issues}


def mutation_report() -> dict[str, Any]:
    mutations = []
    statuses = ["LIVED", "KILLED", "NOT COVERED", "TIMED OUT", "NOT VIABLE", "SKIPPED", "RUNNABLE"]
    for index in range(80):
        mutations.append(
            {
                "type": "CONDITIONALS_BOUNDARY",
                "status": statuses[index % len(statuses)],
                "line": 11 + (index % 5),
                "column": 7 + (index % 4),
            }
        )
    return {"go_module": MODULE, "files": [{"file_name": "internal/domain/domain.go", "mutations": mutations}], "mutants_total": 80}


def fake_run(command: list[str], cwd: Path | None = None, env: dict[str, str] | None = None, timeout: int | None = None, stdin: str | None = None) -> tuple[int, str]:
    del cwd, env, timeout, stdin
    name = Path(command[0]).name
    if name == "marestail-go-scan":
        return 0, json.dumps(scan_records(command))
    if name == "gofmt":
        return 0, ""
    if name == "golangci-lint":
        report = flag_value(command, "--output.json.path")
        if report is not None:
            Path(report).write_text(json.dumps(lint_report()))
        return 1, ""
    if name == "gremlins":
        report = flag_value(command, "--output")
        if report is not None:
            Path(report).write_text(json.dumps(mutation_report()))
        return 0, ""
    if len(command) > 1 and command[1] == "env":
        return 0, json.dumps({"GOVERSION": "go1.27.0", "GOROOT": "/usr/lib/go", "GOBIN": "", "GOPATH": ""})
    if "edit" in command:
        return 0, json.dumps({"Module": {"Path": MODULE}, "Go": "1.25"})
    if "version" in command:
        return 0, pin_text(command[-1])
    if "test" in command:
        profile = flag_value(command, "-coverprofile")
        if profile is not None:
            Path(profile).write_text(state["profile"])
        return 0, state["events"]
    return 0, ""


