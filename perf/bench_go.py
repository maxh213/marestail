def cold(key: str, fn: Call) -> None:
    state["ctx"].memo.pop(key, None)
    fn()


def found_go() -> None:
    patterns = docs.ENV_PATTERNS
    extra = getattr(docs, "GO_ENV_PATTERNS", None)
    if extra is not None and "extra" in inspect.signature(docs.found).parameters:
        docs.found(state["ctx"], patterns, extra)
        return
    docs.found(state["ctx"], patterns)


